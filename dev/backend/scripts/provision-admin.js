// Provision one explicitly named bootstrap administrator from a hash-only env.
require("../src/config/env-file").loadEnv();

const { whenReady, getState, saveState, shutdownStore } = require("../src/data/store");
const { ensureAdminUsers } = require("../src/domain/admin-accounts");

function fail(message) {
  console.error(message);
  process.exitCode = 1;
}

async function main() {
  const username = String(process.env.TGG_ADMIN_USERNAME || "super_admin").trim();
  const name = String(process.env.TGG_ADMIN_NAME || "Super Administrator").trim();
  const hash = String(process.env.TGG_ADMIN_PASSWORD_HASH || "").trim();
  if (!/^[a-zA-Z0-9_.-]{3,40}$/.test(username)) return fail("TGG_ADMIN_USERNAME must contain 3 to 40 letters, digits, dots, underscores or hyphens");
  if (!name || name.length > 50) return fail("TGG_ADMIN_NAME must contain 1 to 50 characters");
  if (!/^scrypt:[a-f0-9]{32}:[a-f0-9]{64}$/i.test(hash)) {
    return fail("TGG_ADMIN_PASSWORD_HASH must be a salted scrypt hash generated by hash-password.js");
  }

  await whenReady();
  const state = getState();
  const accounts = ensureAdminUsers(state);
  const bootstrapAccounts = accounts.filter(item =>
    item?.id === "super_admin"
    || item?.username === "super_admin"
    || item?.roleId === "super_admin"
    || item?.roleIds?.includes("super_admin")
  );
  if (bootstrapAccounts.length !== 1) return fail("Exactly one super-admin bootstrap account is required");
  const account = bootstrapAccounts[0];
  if (accounts.some(item => item !== account && String(item?.username || "").toLowerCase() === username.toLowerCase())) return fail("TGG_ADMIN_USERNAME is already used by another administrator");

  account.username = username;
  account.name = name;
  account.passwordHash = hash;
  account.status = "active";
  account.roleIds = [...new Set([...(account.roleIds || []), "super_admin"])];
  delete account.securityLockReason;
  await saveState();
  console.log(`Provisioned active super admin '${username}'. Password material was not printed.`);
}

main().catch(error => {
  fail(error?.message || "Administrator provisioning failed");
}).finally(() => shutdownStore().catch(() => {}));
